-- 0) 기존 테이블 삭제: 자식 → 부모 순서, 없는 테이블은 건너뜀
BEGIN
  FOR t IN (
    SELECT 'TB_QSTN_ANS' AS NM, 1 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_ATCH_FILE' AS NM, 2 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_RQT_MTTR' AS NM, 3 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_BID_RSLT' AS NM, 4 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_EVL_ARTCL' AS NM, 5 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_SBMSN_DCMNT' AS NM, 6 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_TOC' AS NM, 7 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_PRP_TMMBR' AS NM, 8 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_PTCP_TEAM' AS NM, 9 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_SCHDL' AS NM, 10 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_NOTI' AS NM, 11 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_PBANC_PRCS_HSTRY' AS NM, 12 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_BID_PBANC' AS NM, 13 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_USER' AS NM, 14 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_TEAM' AS NM, 15 AS ORD FROM DUAL
    UNION ALL SELECT 'TB_COM_CD' AS NM, 16 AS ORD FROM DUAL
    ORDER BY ORD
  ) LOOP
    FOR u IN (SELECT 1 FROM user_tables WHERE table_name = t.NM) LOOP
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.NM || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
  END LOOP;
END;
/

