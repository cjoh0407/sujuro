  QSTN_ANS_SN     NUMBER(22)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
  PBANC_SN        NUMBER(22)           NOT NULL,
  QSTN_ANS_SE_CD  CHAR(5)              NOT NULL,
  QSTN_CN         VARCHAR2(4000 CHAR)  NOT NULL,
  ANS_CN          VARCHAR2(4000 CHAR),
  ANSWR_ID        VARCHAR2(20 CHAR),
  TOC_SN          NUMBER(22),
  CCRNC_YN        CHAR(1),
  WRTR_ID         VARCHAR2(20 CHAR)    NOT NULL,
  WRT_DT          DATE                 DEFAULT SYSDATE  NOT NULL,
  CONSTRAINT PK_QSTN_ANS PRIMARY KEY (QSTN_ANS_SN),
  CONSTRAINT CK_QSTN_ANS_CCRNC_YN CHECK (CCRNC_YN IN ('Y','N')),
  CONSTRAINT FK_QSTN_ANS_PBANC_SN FOREIGN KEY (PBANC_SN) REFERENCES TB_BID_PBANC (PBANC_SN),
  CONSTRAINT FK_QSTN_ANS_ANSWR_ID FOREIGN KEY (ANSWR_ID) REFERENCES TB_USER (USER_ID),
  CONSTRAINT FK_QSTN_ANS_TOC_SN FOREIGN KEY (TOC_SN) REFERENCES TB_TOC (TOC_SN),
  CONSTRAINT FK_QSTN_ANS_WRTR_ID FOREIGN KEY (WRTR_ID) REFERENCES TB_USER (USER_ID)
);
COMMENT ON TABLE TB_QSTN_ANS IS '질문답변';
COMMENT ON COLUMN TB_QSTN_ANS.QSTN_ANS_SN IS '질문답변일련번호 - 자동 증가';
COMMENT ON COLUMN TB_QSTN_ANS.PBANC_SN IS '공고일련번호';
COMMENT ON COLUMN TB_QSTN_ANS.QSTN_ANS_SE_CD IS '질문답변구분코드 - 공통코드 QNASE (예상/발표)';
COMMENT ON COLUMN TB_QSTN_ANS.QSTN_CN IS '질문내용';
COMMENT ON COLUMN TB_QSTN_ANS.ANS_CN IS '답변내용';
COMMENT ON COLUMN TB_QSTN_ANS.ANSWR_ID IS '답변자아이디 - 답변 담당자';
COMMENT ON COLUMN TB_QSTN_ANS.TOC_SN IS '목차일련번호 - 관련 목차';
COMMENT ON COLUMN TB_QSTN_ANS.CCRNC_YN IS '일치여부 - 발표 Q&A가 예상 질문과 일치했는지';
COMMENT ON COLUMN TB_QSTN_ANS.WRTR_ID IS '작성자아이디';
COMMENT ON COLUMN TB_QSTN_ANS.WRT_DT IS '작성일시';

