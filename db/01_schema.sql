-- 평가표업로드 (TB_EVL_TBL_UPLD)  ← 먼저 필요: 사용자, 업체평가결과, 첨부파일
-- 나라장터 「기술평가점수 조회」 엑셀을 업체별로 올린 기록. 다시 올리면 행을 더하고
-- 이전 행은 LAST_YN='N' 으로 남긴다.
CREATE TABLE TB_EVL_TBL_UPLD (
  EVL_TBL_UPLD_SN    NUMBER(22)         GENERATED BY DEFAULT ON NULL AS IDENTITY,
  CO_EVL_RSLT_SN     NUMBER(22)         NOT NULL,
  FILE_SN            NUMBER(22)         NOT NULL,
  CMSNR_CNT          NUMBER(4),
  LAST_YN            CHAR(1)            DEFAULT 'Y'  NOT NULL,
  RGTR_ID            VARCHAR2(20 CHAR)  NOT NULL,
  REG_DT             DATE               DEFAULT SYSDATE  NOT NULL,
  CONSTRAINT PK_EVL_TBL_UPLD PRIMARY KEY (EVL_TBL_UPLD_SN),
  CONSTRAINT CK_EVL_TBL_UPLD_LAST_YN CHECK (LAST_YN IN ('Y','N')),
  CONSTRAINT FK_EVL_TBL_UPLD_CO_SN FOREIGN KEY (CO_EVL_RSLT_SN) REFERENCES TB_CO_EVL_RSLT (CO_EVL_RSLT_SN),
  CONSTRAINT FK_EVL_TBL_UPLD_FILE_SN FOREIGN KEY (FILE_SN) REFERENCES TB_ATCH_FILE (FILE_SN),
  CONSTRAINT FK_EVL_TBL_UPLD_RGTR_ID FOREIGN KEY (RGTR_ID) REFERENCES TB_USER (USER_ID)
);
COMMENT ON TABLE TB_EVL_TBL_UPLD IS '평가표업로드';
COMMENT ON COLUMN TB_EVL_TBL_UPLD.EVL_TBL_UPLD_SN IS '평가표업로드일련번호 - 자동 증가';
COMMENT ON COLUMN TB_EVL_TBL_UPLD.CO_EVL_RSLT_SN IS '업체평가결과일련번호 - 어느 업체의 평가표인지';
COMMENT ON COLUMN TB_EVL_TBL_UPLD.FILE_SN IS '파일일련번호 - 올린 엑셀 원본. 파일구분 FL070';
COMMENT ON COLUMN TB_EVL_TBL_UPLD.CMSNR_CNT IS '평가위원수 - 엑셀에서 읽은 위원 수. 공고마다 다르다';
COMMENT ON COLUMN TB_EVL_TBL_UPLD.LAST_YN IS '최종여부 - 다시 올리면 이전 행은 N';
COMMENT ON COLUMN TB_EVL_TBL_UPLD.RGTR_ID IS '등록자아이디 - 올린 경영지원실 직원';
COMMENT ON COLUMN TB_EVL_TBL_UPLD.REG_DT IS '등록일시';

-- 위원별점수 (TB_EVL_CMSNR_SCR)  ← 먼저 필요: 업체평가결과, 평가항목
-- 엑셀의 원점수만 넣는다. 평균 등 계산값은 저장하지 않고 조회할 때 계산한다.
CREATE TABLE TB_EVL_CMSNR_SCR (
  CMSNR_SCR_SN       NUMBER(22)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
  CO_EVL_RSLT_SN     NUMBER(22)   NOT NULL,
  EVL_ARTCL_SN       NUMBER(22)   NOT NULL,
  CMSNR_NO           NUMBER(4)    NOT NULL,
  EVL_SCR            NUMBER(10,3) NOT NULL,
  CONSTRAINT PK_EVL_CMSNR_SCR PRIMARY KEY (CMSNR_SCR_SN),
  CONSTRAINT UK_EVL_CMSNR_SCR UNIQUE (CO_EVL_RSLT_SN, EVL_ARTCL_SN, CMSNR_NO),
  CONSTRAINT FK_EVL_CMSNR_SCR_CO_SN FOREIGN KEY (CO_EVL_RSLT_SN) REFERENCES TB_CO_EVL_RSLT (CO_EVL_RSLT_SN),
  CONSTRAINT FK_EVL_CMSNR_SCR_ARTCL_SN FOREIGN KEY (EVL_ARTCL_SN) REFERENCES TB_EVL_ARTCL (EVL_ARTCL_SN)
);
COMMENT ON TABLE TB_EVL_CMSNR_SCR IS '위원별점수';
COMMENT ON COLUMN TB_EVL_CMSNR_SCR.CMSNR_SCR_SN IS '위원별점수일련번호 - 자동 증가';
COMMENT ON COLUMN TB_EVL_CMSNR_SCR.CO_EVL_RSLT_SN IS '업체평가결과일련번호';
COMMENT ON COLUMN TB_EVL_CMSNR_SCR.EVL_ARTCL_SN IS '평가항목일련번호';
COMMENT ON COLUMN TB_EVL_CMSNR_SCR.CMSNR_NO IS '평가위원번호 - 엑셀의 "평가위원N" 에서 N. 위원 신분은 엑셀에 없다';
COMMENT ON COLUMN TB_EVL_CMSNR_SCR.EVL_SCR IS '평가점수 - 위원이 준 원점수. 배점을 넘으면 업로드 때 막는다';
