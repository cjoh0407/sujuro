-- 하는 일
--   1) 목차양식 TB_TOC_FORM: 테이블은 이미 있음 → 설명(코멘트)만 단다
--   2) TB_TOC: 목차양식일련번호·목차구분코드 추가, 시작·종료쪽번호 삭제(조견표로 이동)
--   3) 기존 공통 목차(PBANC_SN이 NULL인 행)를 "(샘플) 기본 목차" 양식에 연결
--   4) TB_TOC: 사업건 목차와 양식 항목 중 하나만 채우도록 CK_TOC_OWNER 추가
--   5) 조견표 TB_EVL_TOC_MPNG 생성
--   6) TB_BID_PBANC: 사전규격번호(가칭) 추가 + 조회용 인덱스
--   7) 공통코드: 목차구분 TOCSE, 목차양식구분 TFMSE 추가, FL040 설명 변경
--
-- 하지 않는 일 (DB v2.0 전체 재생성 때 함께 한다)
--   - TB_USER 외부인력여부(OTSD_MNPW_YN)·회사명(CO_NM) 삭제: 지금 지우면 AuthMapper.xml 로그인 쿼리가 실패한다
--   - 공통코드 AU050·JG030·PT030 삭제
-- ============================================================

-- ------------------------------------------------------------
-- 1) 목차양식 TB_TOC_FORM (테이블은 이미 생성됨)
--    만약 아래 COMMENT에서 ORA-00942(테이블 없음)가 나면, 이 주석 안의 CREATE 문을 먼저 실행한다.
--    CREATE TABLE TB_TOC_FORM (
--      TOC_FORM_SN     NUMBER(22)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
--      TOC_FORM_NM     VARCHAR2(100 CHAR)  NOT NULL,
--      TOC_FORM_SE_CD  CHAR(5)             NOT NULL,
--      RGTR_ID         VARCHAR2(20 CHAR),
--      USE_YN          CHAR(1)             DEFAULT 'Y'  NOT NULL,
--      REG_DT          DATE                DEFAULT SYSDATE  NOT NULL,
--      CONSTRAINT PK_TOC_FORM PRIMARY KEY (TOC_FORM_SN),
--      CONSTRAINT CK_TOC_FORM_USE_YN CHECK (USE_YN IN ('Y','N')),
--      CONSTRAINT FK_TOC_FORM_RGTR_ID FOREIGN KEY (RGTR_ID) REFERENCES TB_USER (USER_ID)
--    );
-- ------------------------------------------------------------
COMMENT ON TABLE TB_TOC_FORM IS '목차양식';
COMMENT ON COLUMN TB_TOC_FORM.TOC_FORM_SN IS '목차양식일련번호 - 자동 증가 (가칭)';
COMMENT ON COLUMN TB_TOC_FORM.TOC_FORM_NM IS '목차양식명 - 예: 대법원 양식 (가칭)';
COMMENT ON COLUMN TB_TOC_FORM.TOC_FORM_SE_CD IS '목차양식구분코드 - 공통코드 TFMSE (기본 양식/커스텀) (가칭)';
COMMENT ON COLUMN TB_TOC_FORM.RGTR_ID IS '등록자아이디 - 커스텀 양식을 저장한 사람, 기본 양식은 NULL';
COMMENT ON COLUMN TB_TOC_FORM.USE_YN IS '사용여부 - N이면 불러오기 목록에서 숨김';
COMMENT ON COLUMN TB_TOC_FORM.REG_DT IS '등록일시';

-- ------------------------------------------------------------
-- 2) TB_TOC 컬럼 변경 (기존 행의 목차구분코드는 모두 제안서 TC010이 된다)
-- ------------------------------------------------------------
ALTER TABLE TB_TOC ADD (TOC_FORM_SN NUMBER(22), TOC_SE_CD CHAR(5) DEFAULT 'TC010' NOT NULL);

ALTER TABLE TB_TOC ADD CONSTRAINT FK_TOC_TOC_FORM_SN FOREIGN KEY (TOC_FORM_SN) REFERENCES TB_TOC_FORM (TOC_FORM_SN);

ALTER TABLE TB_TOC DROP (BGNG_PAGE_NO, END_PAGE_NO);

COMMENT ON COLUMN TB_TOC.PBANC_SN IS '공고일련번호 - 사업건 목차일 때';
COMMENT ON COLUMN TB_TOC.TOC_FORM_SN IS '목차양식일련번호 - 목차 양식의 항목일 때 (가칭)';
COMMENT ON COLUMN TB_TOC.TOC_SE_CD IS '목차구분코드 - 공통코드 TOCSE (제안서/제안요약서) (가칭)';
COMMENT ON COLUMN TB_TOC.PIC_ID IS '담당자아이디 - 목차 담당자 (제안팀원 중에서 지정)';

-- ------------------------------------------------------------
-- 3) 기존 공통 목차를 "(샘플) 기본 목차" 양식에 연결
--    양식 방식(기관 대표 양식 / 커스텀만)은 멘토 상담 후 정한다. 그때까지 불러오기 테스트용으로 쓴다.
-- ------------------------------------------------------------
INSERT INTO TB_TOC_FORM (TOC_FORM_NM, TOC_FORM_SE_CD, USE_YN)
SELECT '(샘플) 기본 목차', 'TF010', 'Y' FROM DUAL
 WHERE EXISTS (SELECT 1 FROM TB_TOC WHERE PBANC_SN IS NULL AND TOC_FORM_SN IS NULL)
   AND NOT EXISTS (SELECT 1 FROM TB_TOC_FORM WHERE TOC_FORM_NM = '(샘플) 기본 목차');

UPDATE TB_TOC
   SET TOC_FORM_SN = (SELECT MIN(TOC_FORM_SN) FROM TB_TOC_FORM WHERE TOC_FORM_NM = '(샘플) 기본 목차')
 WHERE PBANC_SN IS NULL AND TOC_FORM_SN IS NULL;

COMMIT;

-- ------------------------------------------------------------
-- 4) 사업건 목차(PBANC_SN)와 양식 항목(TOC_FORM_SN) 중 하나만 채운다
-- ------------------------------------------------------------
ALTER TABLE TB_TOC ADD CONSTRAINT CK_TOC_OWNER CHECK (
  (PBANC_SN IS NOT NULL AND TOC_FORM_SN IS NULL) OR (PBANC_SN IS NULL AND TOC_FORM_SN IS NOT NULL));

-- ------------------------------------------------------------
-- 5) 조견표 TB_EVL_TOC_MPNG (평가 항목별 목차와 시작·끝 쪽, FR-071·072)
--    목차를 지울 때 이 테이블의 연결도 정리하므로 지금 만들어 둔다.
-- ------------------------------------------------------------
CREATE TABLE TB_EVL_TOC_MPNG (
  EVL_ARTCL_SN  NUMBER(22)         NOT NULL,
  TOC_SN        NUMBER(22)         NOT NULL,
  BGNG_PAGE_NO  VARCHAR2(20 CHAR),
  END_PAGE_NO   VARCHAR2(20 CHAR),
  REG_DT        DATE               DEFAULT SYSDATE  NOT NULL,
  CONSTRAINT PK_EVL_TOC_MPNG PRIMARY KEY (EVL_ARTCL_SN, TOC_SN),
  CONSTRAINT FK_EVL_TOC_MPNG_EVL_ARTCL_SN FOREIGN KEY (EVL_ARTCL_SN) REFERENCES TB_EVL_ARTCL (EVL_ARTCL_SN),
  CONSTRAINT FK_EVL_TOC_MPNG_TOC_SN FOREIGN KEY (TOC_SN) REFERENCES TB_TOC (TOC_SN)
);

COMMENT ON TABLE TB_EVL_TOC_MPNG IS '평가항목목차매핑 - 조견표';
COMMENT ON COLUMN TB_EVL_TOC_MPNG.EVL_ARTCL_SN IS '평가항목일련번호';
COMMENT ON COLUMN TB_EVL_TOC_MPNG.TOC_SN IS '목차일련번호 - 해당 내용이 들어 있는 제안서 목차';
COMMENT ON COLUMN TB_EVL_TOC_MPNG.BGNG_PAGE_NO IS '시작쪽번호 - 최종 제안서 기준';
COMMENT ON COLUMN TB_EVL_TOC_MPNG.END_PAGE_NO IS '종료쪽번호 - 최종 제안서 기준';
COMMENT ON COLUMN TB_EVL_TOC_MPNG.REG_DT IS '등록일시';

-- ------------------------------------------------------------
-- 6) TB_BID_PBANC 사전규격번호 (가칭) + 조회용 인덱스 (재공고가 같은 번호를 쓸 수 있어 UK는 두지 않는다)
-- ------------------------------------------------------------
ALTER TABLE TB_BID_PBANC ADD (PRE_SPEC_NO VARCHAR2(20 CHAR));

CREATE INDEX IX_BID_PBANC_PRE_SPEC_NO ON TB_BID_PBANC (PRE_SPEC_NO);

COMMENT ON COLUMN TB_BID_PBANC.PRE_SPEC_NO IS '사전규격번호 (가칭) - 본공고부터 등록하면 NULL, 값 유무로 사전규격 연결 여부 판단. 재공고가 같은 번호를 쓸 수 있어 UK 없음';

-- ------------------------------------------------------------
-- 7) 공통코드 (02_code_data.sql v2.3과 같은 값, 이미 있으면 넣지 않는다)
-- ------------------------------------------------------------
INSERT INTO TB_COM_CD (GROUP_CD, CD, CD_GROUP_NM, CD_NM, SORT_SEQ, USE_YN)
SELECT 'TOCSE', 'TC010', '목차구분', '제안서', 1, 'Y' FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM TB_COM_CD WHERE GROUP_CD = 'TOCSE' AND CD = 'TC010');
INSERT INTO TB_COM_CD (GROUP_CD, CD, CD_GROUP_NM, CD_NM, SORT_SEQ, USE_YN)
SELECT 'TOCSE', 'TC020', '목차구분', '제안요약서', 2, 'Y' FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM TB_COM_CD WHERE GROUP_CD = 'TOCSE' AND CD = 'TC020');
INSERT INTO TB_COM_CD (GROUP_CD, CD, CD_GROUP_NM, CD_NM, SORT_SEQ, USE_YN)
SELECT 'TFMSE', 'TF010', '목차양식구분', '기본 양식', 1, 'Y' FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM TB_COM_CD WHERE GROUP_CD = 'TFMSE' AND CD = 'TF010');
INSERT INTO TB_COM_CD (GROUP_CD, CD, CD_GROUP_NM, CD_NM, SORT_SEQ, USE_YN)
SELECT 'TFMSE', 'TF020', '목차양식구분', '커스텀', 2, 'Y' FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM TB_COM_CD WHERE GROUP_CD = 'TFMSE' AND CD = 'TF020');

UPDATE TB_COM_CD SET CD_EXPLN = '제안요약서 목차별 파일 (목차일련번호를 채워 저장)'
 WHERE GROUP_CD = 'FILSE' AND CD = 'FL040';

COMMIT;

