-- 참고자료 (TB_REF_FILE)
-- 주관팀끼리 폰트·이미지·문서를 같이 쓰는 자료실. 팀일련번호가 같은 사람만 보고 올린다. 삭제는 숨김(원본 보관).
CREATE TABLE TB_REF_FILE (
  REF_FILE_SN    NUMBER(22)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TEAM_SN        NUMBER(22)          NOT NULL,
  REF_SE_CD      CHAR(5)             NOT NULL,
  ORGNL_FILE_NM  VARCHAR2(300 CHAR)  NOT NULL,
  STRG_FILE_NM   VARCHAR2(100 CHAR)  NOT NULL,
  FILE_PATH_NM   VARCHAR2(300 CHAR)  NOT NULL,
  FILE_SZ        NUMBER(14),
  FILE_EXTN_NM   VARCHAR2(5 CHAR),
  MEMO_CN        VARCHAR2(500 CHAR),
  RGTR_ID        VARCHAR2(20 CHAR)   NOT NULL,
  REG_DT         DATE                DEFAULT SYSDATE NOT NULL,
  DEL_YN         CHAR(1)             DEFAULT 'N' NOT NULL,
  DLTR_ID        VARCHAR2(20 CHAR),
  DEL_DT         DATE,
  CONSTRAINT PK_REF_FILE PRIMARY KEY (REF_FILE_SN),
  CONSTRAINT CK_REF_FILE_DEL_YN CHECK (DEL_YN IN ('Y','N')),
  CONSTRAINT FK_REF_FILE_TEAM_SN FOREIGN KEY (TEAM_SN) REFERENCES TB_TEAM (TEAM_SN),
  CONSTRAINT FK_REF_FILE_RGTR_ID FOREIGN KEY (RGTR_ID) REFERENCES TB_USER (USER_ID)
);
CREATE INDEX IX_REF_FILE_TEAM ON TB_REF_FILE (TEAM_SN, DEL_YN);
COMMENT ON TABLE TB_REF_FILE IS '참고자료';
COMMENT ON COLUMN TB_REF_FILE.REF_FILE_SN IS '참고자료일련번호 - 자동 증가';
COMMENT ON COLUMN TB_REF_FILE.TEAM_SN IS '팀일련번호 - 이 팀 사람만 본다';
COMMENT ON COLUMN TB_REF_FILE.REF_SE_CD IS '참고자료구분코드 - REFSE (폰트 RF010, 이미지 RF020, 문서 RF030, 기타 RF040)';
COMMENT ON COLUMN TB_REF_FILE.ORGNL_FILE_NM IS '원본파일명 - 올린 사람이 쓴 이름';
COMMENT ON COLUMN TB_REF_FILE.STRG_FILE_NM IS '저장파일명 - 겹치지 않게 만든 이름';
COMMENT ON COLUMN TB_REF_FILE.FILE_PATH_NM IS '파일경로명 - 저장 폴더 아래 상대 경로';
COMMENT ON COLUMN TB_REF_FILE.FILE_SZ IS '파일크기 - 바이트';
COMMENT ON COLUMN TB_REF_FILE.FILE_EXTN_NM IS '파일확장자명';
COMMENT ON COLUMN TB_REF_FILE.MEMO_CN IS '메모내용 - 올릴 때 적는 설명';
COMMENT ON COLUMN TB_REF_FILE.RGTR_ID IS '등록자아이디 - 올린 사람. 삭제는 올린 사람과 팀장만';
COMMENT ON COLUMN TB_REF_FILE.REG_DT IS '등록일시';
COMMENT ON COLUMN TB_REF_FILE.DEL_YN IS '삭제여부 - Y면 화면에서 숨김';
COMMENT ON COLUMN TB_REF_FILE.DLTR_ID IS '삭제자아이디';
COMMENT ON COLUMN TB_REF_FILE.DEL_DT IS '삭제일시';

